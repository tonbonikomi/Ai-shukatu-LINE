import { text } from '@/lib/line/client'

/** 一柳が送る文面をここに集約する。運用しながら直すことになるため */

export const groupInvite = (name: string, inviteUrl: string) =>
  text(
    [
      `${name}さん、登録ありがとうございます！`,
      'バイト案件が流れるグループにご招待します。下のリンクから参加してください。',
      '',
      inviteUrl,
      '',
      '※このリンクはあなた専用です。転送しないでください。',
      '※案件の詳細・応募はこのトーク（1対1）で受け付けます。',
    ].join('\n'),
  )

export const groupNotReady = (name: string) =>
  text(
    [
      `${name}さん、登録ありがとうございます！`,
      'お住まいの地域のグループを準備中です。ご案内できるようになりましたら、こちらからご連絡します。',
    ].join('\n'),
  )

/** 入室時の歓迎。応答メッセージなので通数を消費しない。ルール掲示を兼ねる */
export const welcomeToGroup = () =>
  text(
    [
      'ようこそ！',
      '・案件の詳細と応募は一柳とのトーク（1対1）で受け付けます',
      '・グループ内での勧誘・営業は禁止です',
    ].join('\n'),
  )

/** 未登録のまま入室した人への登録依頼（docs/decisions.md D-002） */
export const askToRegister = (registrationUrl: string) =>
  text(
    [
      'グループへのご参加ありがとうございます。',
      'ご参加にあたって、かんたんな登録（30秒）をお願いしています。',
      '',
      registrationUrl,
      '',
      'お手数ですがご対応をお願いします。',
    ].join('\n'),
  )

/**
 * 友だち追加への応答（応答メッセージなので無料）。
 *
 * 入口リンク経由なら LIFF 側でトークンを持っているので、ここでは案内だけ。
 * 入口リンクを持たずに友だち追加した人は登録できない（招待権は運営が握るため）。
 */
export const followGreeting = () =>
  text(
    [
      '友だち追加ありがとうございます！',
      'ご登録は、お友達から受け取った招待リンクから進めてください。',
      '',
      'リンクをお持ちでない場合は、このトークにその旨をお送りください。',
    ].join('\n'),
  )
